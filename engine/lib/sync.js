// Sync: turns configuration into the files Claude Code reads.
//   .claude/agents/*.md      one file per enabled agent (model, effort, tools, skills)
//   .claude/skills/*         Orgtomo playbooks, your org style, approved lessons
//   .claude/settings.json    environment for the Salesforce plugin (telemetry, skills-first)
//   .mcp.json                MCP servers from capabilities.yaml
// Everything here is generated. Change the configuration, not these files.
import fs from 'node:fs';
import path from 'node:path';
import { PLUGIN_ROOT, layout } from './paths.js';
import { orgNames, org as getOrg, loopMax, approvalStages } from './config.js';
import { grantedTools, allowedBrowserHosts } from './guards/mcp.js';
import { lessonsFor } from './learning.js';
import { parse as parseYaml } from './yaml.js';
import { exists, readText, writeText, readJson, writeJson, listFiles, getPath } from './util.js';

const AGENTS_SRC = path.join(PLUGIN_ROOT, 'agents-src');
const SKILLS_SRC = path.join(PLUGIN_ROOT, 'skills-src');
export const agentFileName = (name) => (name === 'lead' ? 'tomo-lead' : name);

function splitTemplate(text) {
  const m = /^---\n([\s\S]*?)\n---\n/.exec(text);
  return m ? { head: parseYaml(m[1]) || {}, body: text.slice(m[0].length) } : { head: {}, body: text };
}

/** Values available to agent templates as {{name}}. */
export function templateVars(cfg, agent) {
  const orgRows = orgNames(cfg).map((n) => { const o = getOrg(cfg, n); return `| ${n} | ${o.alias} | ${o.role} | ${o.role === 'production' ? 'read-only, masked' : o.role === 'build' ? 'agents build and test here' : o.role === 'test' ? 'humans deploy; agents retest' : 'read-only'} |`; });
  const s = cfg.safety;
  return {
    company: cfg.orgs.company || 'this company',
    build_org: cfg.pipeline.build_org,
    build_alias: getOrg(cfg, cfg.pipeline.build_org).alias,
    brain_base: cfg.pipeline.brain_base,
    source_dir: `${cfg.pipeline.source_dir || 'source'}/${cfg.pipeline.build_org}`,
    orgs_table: `| Org | Alias | Role | What happens there |\n|---|---|---|---|\n${orgRows.join('\n')}`,
    targets: (cfg.pipeline.targets || []).map((t) => `${t.org} (${t.tool})`).join(' -> ') || 'none',
    loop_max: String(loopMax(cfg)),
    approvals: approvalStages(cfg).join(', '),
    email_mode: s.email_mode,
    allowed_emails: (s.allowed_emails || []).join(', ') || '(none)',
    allowed_phones: (s.allowed_phones || []).join(', ') || '(none)',
    test_person: `${s.test_person?.first_name || 'Test'} ${s.test_person?.last_name || 'User'}, company "${s.test_person?.company || 'Test Account'}"`,
    doc_hosts: (s.official_doc_hosts || []).join(', '),
    sf_skills: (cfg.capabilities.sf_skills?.[agent] || []).map((x) => `\`${x}\``).join(', ') || '(none)',
    flow_generator: getPath(cfg.features, 'sf_skills.flow_generator') ? 'on (build org only)' : 'off',
    people: cfg.features.people_profiles?.enabled ? 'on' : 'off',
    meetings: cfg.features.meetings?.enabled ? `on (${cfg.features.meetings.provider})` : 'off',
  };
}
const fill = (text, vars) => text.replace(/\{\{(\w+)\}\}/g, (m, k) => (k in vars ? vars[k] : m));

/** Build the Markdown of one agent file. */
export function renderAgent(cfg, name) {
  const src = path.join(AGENTS_SRC, `${name}.md`);
  const { head, body } = splitTemplate(readText(src));
  const def = cfg.agents.agents[name];
  const grant = cfg.capabilities.grants?.[name] || { tools: ['Read', 'Grep', 'Glob'] };
  const tools = [...(grant.tools || [])];
  if ((cfg.capabilities.sf_skills?.[name] || []).length && !tools.includes('Skill')) tools.push('Skill');
  if (name === 'lead') {
    const team = Object.entries(cfg.agents.agents).filter(([n, d]) => n !== 'lead' && d.enabled !== false && (n !== 'notetaker' || cfg.features.meetings?.enabled)).map(([n]) => n);
    tools.unshift(`Agent(${team.join(', ')})`);
  }
  tools.push(...grantedTools(cfg, name));
  const skills = [...(head.skills || [])];
  if (head.style_skills) skills.push('org-naming', 'org-comments', 'org-format');
  skills.push(`lessons-${name}`);
  const lite = cfg.agents.max_turns?.default ?? 60;
  const front = [
    '---',
    `name: ${agentFileName(name)}`,
    `description: ${JSON.stringify(head.description || `Orgtomo ${name}`)}`,
    `tools: ${[...new Set(tools)].join(', ')}`,
    `model: ${def.model}`,
    `effort: ${def.effort}`,
    `maxTurns: ${head.max_turns || lite}`,
    'skills:',
    ...skills.map((s) => `  - ${s}`),
    ...(head.color ? [`color: ${head.color}`] : []),
    '---',
  ].join('\n');
  return `${front}\n<!-- Generated by "orgtomo sync" from agents-src/${name}.md and orgtomo.config. Do not edit. -->\n${fill(body, templateVars(cfg, name))}`;
}

// ------------------------------------------------------------------ generated skills

const skillHead = (name, description) => `---\nname: ${name}\ndescription: ${JSON.stringify(description)}\nuser-invocable: false\n---\n<!-- Generated by "orgtomo sync". Change orgtomo.config/conventions.yaml or approve lessons instead. -->\n`;

function namingSkill(cfg) {
  const n = cfg.conventions.naming || {};
  const row = (label, v) => (v ? `| ${label} | \`${v}\` |` : null);
  const el = Object.entries(n.flow_element || {}).map(([k, v]) => row(`Flow element: ${k}`, v));
  const rows = [row('Apex class', n.apex_class), row('Apex test class', n.apex_test), row('Apex trigger', n.apex_trigger), row('Flow API name', n.flow), ...el, row('Custom field', n.custom_field), row('Custom object', n.custom_object), row('LWC bundle', n.lwc)].filter(Boolean);
  return `${skillHead('org-naming', "This org's naming rules. Apply to every new component and element name.")}# Naming rules of this org\n\nThese patterns are checked by the naming gates. A new name that does not match is rejected, so match them the first time.\n\n| What | Pattern (regular expression) |\n|---|---|\n${rows.join('\n')}\n\n- Existing components keep their names. Never rename something to fit the rule.\n- Test records need descriptive names of at least ${n.test_record_min_words ?? 3} words, not just the ticket key.\n- If a rule does not fit a real need, say so in the plan as a deviation. Do not silently break it.\n`;
}
function commentsSkill(cfg) {
  const c = cfg.conventions.comments || {};
  return `${skillHead('org-comments', "This org's comment rules for Apex and Flow. Apply to every file you create or change.")}# Comment rules of this org\n\n- New Apex classes and triggers start with a doc comment (\`/** ... */\`)${c.class_header_required ? ' that contains: ' + (c.class_header_tags || []).map((t) => `\`${t}\``).join(', ') : ''}.\n- ${c.change_line_required ? `Every modified Apex file gets one change line in exactly this form, with today's date and the ticket key:\n\n  \`${c.change_line}\`\n\n  Author value: \`${c.author || 'Orgtomo'}\`.` : 'No change line is required.'}\n- ${c.flow_description_required ? 'Every Flow you create or change has a filled Description that says what it does and names the ticket.' : 'Flow descriptions are optional.'}\n- Comments explain why, not what. No commented-out code.\n`;
}
function formatSkill(cfg) {
  const f = cfg.conventions.format || {};
  const forb = (cfg.conventions.forbidden || []).map((x) => `- **${x.id}**: ${x.why}`).join('\n');
  return `${skillHead('org-format', "This org's code format and forbidden patterns. Apply to every file you create or change.")}# Format rules of this org\n\n- Indent with ${f.indent_style === 'tab' ? 'tabs' : `${f.indent} spaces`}.\n- Lines are at most ${f.max_line} characters.\n- Every new class declares sharing. Default: \`${f.sharing_default}\`.\n- Triggers: ${f.trigger_pattern}.\n- Match the style of the file you are editing; do not reformat lines you are not changing.\n\n## Forbidden\n\n${forb || '_None configured._'}\n`;
}
function lessonsSkill(root, name) {
  const lessons = lessonsFor(root, name);
  const body = lessons.length
    ? lessons.map((l) => `- **${l.id}** (${l.type === 'avoid' ? 'do not repeat' : 'keep doing'}) ${l.rule}\n  Why: ${l.why}${l.recurrences ? `\n  This mistake happened again ${l.recurrences} time(s) after the lesson was given. Take extra care.` : ''}`).join('\n')
    : '_No lessons yet. They appear here after real, recorded mistakes or good results on tickets._';
  return `${skillHead(`lessons-${name}`, `Lessons the ${name} learned on earlier tickets in this org. Each is backed by recorded evidence. Apply all of them.`)}# Lessons for the ${name}\n\nEvery lesson below comes from something that really happened here and was recorded by the engine (a failed gate, a human rejection, a reviewer finding, or the human's own words). Apply each one. Details are in the vault under \`learning/lessons/\`.\n\n${body}\n`;
}

// ------------------------------------------------------------------ MCP servers

/** .mcp.json content from capabilities.yaml. */
export function renderMcp(root, cfg) {
  const out = {};
  for (const [name, def] of Object.entries(cfg.capabilities.mcp_servers || {})) {
    const server = { ...def };
    delete server.when;
    if (name === 'granola' && !(cfg.features.meetings?.enabled && cfg.features.meetings.provider === 'granola')) continue;
    if (name === 'atlassian' && cfg.features.tracker?.provider !== 'atlassian') continue;
    if (name === 'playwright') {
      if (cfg.safety.browser?.provider !== 'playwright') continue;
      const args = [...(server.args || [])];
      if (!args.includes('--user-data-dir')) args.push('--user-data-dir', path.join(root, '.orgtomo', 'browser-profile'));
      if (!args.includes('--output-dir')) args.push('--output-dir', path.join(root, '.orgtomo', 'browser-out'));
      out[name] = { ...server, args };
      continue;
    }
    out[name] = server;
  }
  return { mcpServers: out };
}

// ------------------------------------------------------------------ sync

/**
 * Regenerate everything. Idempotent.
 * @returns {{written: string[], removed: string[], notes: string[]}}
 */
export function sync(root, cfg) {
  const L = layout(root);
  const written = [];
  const removed = [];
  const notes = [];
  const put = (file, text) => {
    if (!exists(file) || readText(file) !== text) { writeText(file, text); written.push(path.relative(root, file)); }
  };

  const agentsDir = path.join(L.claude, 'agents');
  const wanted = new Set();
  for (const [name, def] of Object.entries(cfg.agents.agents)) {
    if (def.enabled === false) continue;
    if (name === 'notetaker' && !cfg.features.meetings?.enabled) continue;
    if (!exists(path.join(AGENTS_SRC, `${name}.md`))) { notes.push(`No template for agent "${name}"; skipped.`); continue; }
    const file = `${agentFileName(name)}.md`;
    wanted.add(file);
    put(path.join(agentsDir, file), renderAgent(cfg, name));
  }
  for (const f of exists(agentsDir) ? fs.readdirSync(agentsDir) : []) {
    if (!wanted.has(f) && readText(path.join(agentsDir, f)).includes('Generated by "orgtomo sync"')) { fs.rmSync(path.join(agentsDir, f)); removed.push(`.claude/agents/${f}`); }
  }

  const skillsDir = path.join(L.claude, 'skills');
  for (const f of listFiles(SKILLS_SRC)) put(path.join(skillsDir, f), readText(path.join(SKILLS_SRC, f)));
  put(path.join(skillsDir, 'org-naming', 'SKILL.md'), namingSkill(cfg));
  put(path.join(skillsDir, 'org-comments', 'SKILL.md'), commentsSkill(cfg));
  put(path.join(skillsDir, 'org-format', 'SKILL.md'), formatSkill(cfg));
  for (const name of Object.keys(cfg.agents.agents)) put(path.join(skillsDir, `lessons-${name}`, 'SKILL.md'), lessonsSkill(root, name));

  const settingsFile = path.join(L.claude, 'settings.json');
  const settings = readJson(settingsFile, {});
  const env = { ...(settings.env || {}) };
  const sfs = cfg.features.sf_skills || {};
  if (sfs.telemetry) { delete env.DO_NOT_TRACK; delete env.SF_DISABLE_TELEMETRY; } else { env.DO_NOT_TRACK = 'true'; env.SF_DISABLE_TELEMETRY = 'true'; }
  env.SF_PLUGIN_SKILLS_FIRST = sfs.skills_first || 'enforce';
  delete env.SFDX_AUTO_DEPLOY;
  const nextSettings = JSON.stringify({ ...settings, env }, null, 2) + '\n';
  if (!exists(settingsFile) || readText(settingsFile) !== nextSettings) { writeText(settingsFile, nextSettings); written.push('.claude/settings.json'); }

  const mcpFile = path.join(root, '.mcp.json');
  const current = readJson(mcpFile, { mcpServers: {} });
  const mine = renderMcp(root, cfg).mcpServers;
  const managed = Object.keys(cfg.capabilities.mcp_servers || {});
  const merged = { ...Object.fromEntries(Object.entries(current.mcpServers || {}).filter(([k]) => !managed.includes(k))), ...mine };
  const nextMcp = JSON.stringify({ ...current, mcpServers: merged }, null, 2) + '\n';
  if (!exists(mcpFile) || readText(mcpFile) !== nextMcp) { writeText(mcpFile, nextMcp); written.push('.mcp.json'); }

  const claudeMd = path.join(root, 'CLAUDE.md');
  const marker = '<!-- orgtomo -->';
  if (!exists(claudeMd) || readText(claudeMd).includes(marker)) {
    put(claudeMd, `${marker}\n# Orgtomo workspace\n\nThis folder is run by Orgtomo. Work on Salesforce tickets happens only through its team of agents.\n\n- Start a session with \`orgtomo start\` (or \`claude --agent tomo-lead\`).\n- The engine decides the order of work: \`orgtomo next <KEY>\`.\n- Production is read-only and masked. Deploys to other orgs are done by a human.\n- Configuration is in \`orgtomo.config/\`; agents cannot change it.\n- Knowledge lives in \`vault/\` (open it in Obsidian).\n`);
  }
  if (!allowedBrowserHosts(cfg).length && cfg.safety.browser?.provider === 'playwright') notes.push('No sandbox host is set in orgs.yaml (host:). The browser stays closed for agents until you add one.');
  return { written, removed, notes };
}
